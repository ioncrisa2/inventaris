<section class="guide-section" aria-labelledby="primer-setup-title">
    <div class="guide-section__header">
        <h2 id="primer-setup-title">Siapkan fondasi koperasi</h2>
        <p>Selesaikan pengaturan dasar sebelum memasukkan data operasional.</p>
    </div>
    <ol class="quick-guide-list">
        <li>
            <h3>Pastikan konteks koperasi Anda benar</h3>
            <p>Periksa nama koperasi pada bagian atas aplikasi. Semua data, role, pengguna, dan laporan yang Anda kelola akan tetap berada dalam lingkup koperasi tersebut.</p>
        </li>
        <li>
            <h3>Lengkapi pengaturan aplikasi</h3>
            <p>Buka <strong>Administrasi → Pengaturan Aplikasi</strong>, lalu lengkapi:</p>
            <ul class="quick-guide-points">
                <li>Identitas resmi, alamat, kontak, dan pimpinan koperasi.</li>
                <li>Pola penomoran inventaris dan jumlah digit nomor urut.</li>
                <li>Hari operasional sebagai dasar absensi dan penggajian.</li>
                <li>Draf serta format terbit slip gaji.</li>
            </ul>
        </li>
        <li>
            <h3>Susun unit kerja</h3>
            <p>Buka <strong>SDM & Kehadiran → Unit Kerja</strong>. Buat unit seperti Keuangan, Operasional, IT, atau Logistik agar pengguna, karyawan, dan aset memiliki penanggung jawab yang jelas.</p>
        </li>
    </ol>
</section>

<section class="guide-section" aria-labelledby="primer-access-title">
    <div class="guide-section__header">
        <h2 id="primer-access-title">Atur role dan pengguna</h2>
        <p>Berikan akses secukupnya berdasarkan tanggung jawab setiap pengguna.</p>
    </div>
    <ol class="quick-guide-list" start="4">
        <li>
            <h3>Buat role custom koperasi</h3>
            <p>Buka <strong>Administrasi → Role & Hak Akses → Tambah Role</strong>. Beri nama yang mudah dikenali, pilih izin yang diperlukan, lalu simpan. Role otomatis terikat ke koperasi Anda dan tidak terlihat oleh koperasi lain.</p>
        </li>
        <li>
            <h3>Daftarkan akun pengguna</h3>
            <p>Buka <strong>Administrasi → Manajemen Pengguna</strong>. Isi identitas akun, pilih unit kerja, lalu tetapkan role custom yang sesuai. Gunakan satu akun untuk satu orang agar riwayat aktivitas tetap dapat ditelusuri.</p>
        </li>
    </ol>
</section>

<section class="guide-section" aria-labelledby="primer-operations-title">
    <div class="guide-section__header">
        <h2 id="primer-operations-title">Jalankan operasional harian</h2>
        <p>Gunakan urutan ini agar data SDM, aset, absensi, dan gaji saling terhubung.</p>
    </div>
    <ol class="quick-guide-list" start="6">
        <li>
            <h3>Masukkan data karyawan</h3>
            <p>Buka <strong>SDM & Kehadiran → Karyawan</strong>. Lengkapi identitas, unit kerja, jabatan, status kerja, gaji pokok, foto, dan dokumen pendukung. Catat mutasi, promosi, serta perubahan gaji melalui riwayat karyawan.</p>
        </li>
        <li>
            <h3>Catat dan beri label inventaris</h3>
            <p>Buka <strong>Manajemen Aset → Inventaris Barang</strong>. Isi data perolehan, lokasi, unit penanggung jawab, dan golongan penyusutan. Unggah bukti pendukung, cetak barcode atau QR Code, lalu catat perubahan kondisi saat audit fisik.</p>
        </li>
        <li>
            <h3>Kelola kalender dan absensi</h3>
            <p>Periksa hari libur serta hari operasional terlebih dahulu. Setelah itu, catat status kehadiran setiap karyawan pada menu <strong>Absensi</strong> agar rekap periode penggajian terbentuk dengan benar.</p>
        </li>
        <li>
            <h3>Proses penggajian</h3>
            <p>Atur tunjangan dan potongan pada <strong>Komponen Gaji</strong>. Buat transaksi gaji per karyawan dan periode, periksa hasil perhitungan, kemudian cetak slip satuan atau massal.</p>
        </li>
        <li>
            <h3>Tinjau dan ekspor laporan</h3>
            <p>Gunakan laporan Inventaris, Penyusutan, Kepegawaian, Absensi, dan Penggajian untuk pemeriksaan berkala. Terapkan filter yang dibutuhkan sebelum mencetak atau mengekspor data ke Excel.</p>
        </li>
    </ol>
</section>
